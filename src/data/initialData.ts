// Helper to get formatted ISO dates (YYYY-MM-DD) for today + offsets
export function getRelativeDate(dayOffset: number): string {
  const d = new Date();
  d.setDate(d.getDate() + dayOffset);
  return d.toISOString().split('T')[0];
}

